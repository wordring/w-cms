// 取引先ページを作れずに黙って壊れます。依存は import で表し、ここは表示だけを
// 足す形にしています——だから**このファイルを消しても機能は消えません**
// （消えるのはログの1語だけ）。
// ─────────────────────────────────────────────────────────────────────────

