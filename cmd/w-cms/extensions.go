// ─────────────────────────────────────────────────────────────────────────
// 拡張の取り付け口（2026-10-20 から作るファイル——ext_*_gen.go）
//
// 2026-10-20 利用者:「できれば、拡張をフォルダに入れてビルドすると入るような仕組みが良いです」。
//
// 拡張は ext/ の下のフォルダ1つで完結します——Go のパッケージ（`init()` で `cms.RegisterExtension` を呼ぶ）と、
// 画面のファイル（`assets/` の JS・CSS・HTML・置き場の決まりで拾う——internal/cms/ext_scripts.go）。
// 取り付け口（blank import の1行）は、ビルドの前に作ります:
//
//	go generate ./cmd/w-cms   … ext/ の下を探して ext_*_gen.go を作り直す（internal/extgen・tools/extgen）
//	go build ./cmd/w-cms      … 拡張は全部入り（既定）
//	go build -tags nomail ./cmd/w-cms    … メールだけ外す（通信箱は残る）
//	go build -tags minimal ./cmd/w-cms   … 素の w-cms（他社へ配る形・業務セットごと外れる）
//
// 作ったファイルはリポジトリに入れます（generate を流さなくても組み立てられるように）。足し忘れ・消し忘れは
// 試験 TestExtensionMountsAreGenerated が見つけます。ビルドタグは拡張が自分で書きます（`//w-cms:build <式>`・無ければ `!minimal`）。
//
// **既定を「入り」にしたのは、忘れて機能が静かに消えるほうが危ないから**です（2026-09-03 の決定）。タグを付け忘れた
// ビルドは案件ページ生成も部材計算も業務語彙も無いまま普通に起動してしまい、気づくのは「発注書を解析しても何も起きない」ときになります。
// 外すのは他社へ配るという**意識的な行為**なので、そちら側にタグを要求します。何が入っているかは起動ログに出ます（拡張セットの行）。
//
// それまで（2026-09-03〜10-20）は、拡張ごとに手で書いた取り付け口（ext_comm.go・ext_contacts.go・ext_mail.go・ext_toho.go）でした。
// そこに書いてあった決めごとは、次のとおり今も生きています。
//   - **メールを外しても他の拡張はビルドできます。** 使う側は通信拡張の口（ext/comm/mail.go の CurrentMailer）に尋ねるだけで、
//     メールの実装を直接 import していないためです（「口と中身を分け、使う側は口に尋ねる」形）。
//   - 通信（ext/comm）はタグを持ちません——`-tags nomail` でも通信箱は残ってほしい（手で作る記録・電話は動く）ためです。
//   - **ext/comm/contacts の側にビルドタグはありません。** タグを付けると「板金は入れたがアドレス帳は外した」組み合わせが作れてしまい、
//     整理が製造台帳の下に社名のページを作れずに黙って壊れます。依存は import で表します（toho が contacts を import している）。
// ─────────────────────────────────────────────────────────────────────────

