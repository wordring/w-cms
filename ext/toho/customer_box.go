// 加工製品の階層の根——`製造`（2026-09-16 にアドレス帳から分かれた。2026-10-16 に `取引先` から `製造` へ改めた）
//
// 2026-10-16 利用者:「取引先フォルダを製造フォルダに変えます。コードと文書も修正してください」。
// 会社そのものを指す「取引先」（取引先の決まり・同じ取引先 など）は、そのままです。
//
// ユーザー決定:「**両方を別の木にする**」。それまで1つの箱（`取引先`）が
// **2つの役目**を兼ねていました:
//
//	取引先／社名／段／装置名称／図面名称   ← 加工製品の階層（東邦の業務の持ち物）
//	取引先／社名／担当者／氏名             ← アドレス帳（通信の持ち物）
//
// **持ち主が違うものが同じ木に同居していた**ので、分けました。アドレス帳は
// `連絡帳`（`ext/comm/contacts`）、加工製品の階層はこの `取引先`（いまの `製造`）です。
//
// ⚠ **2つの木は「社名の題」で結ばれています。** 整理は差出人アドレスから
// アドレス帳に問い合わせて（`contacts.PartnerTitleForAddress`）**題を受け取り**、
// その題のページをこの木に作ります。つまり:
//
//	連絡帳／南北スポーツ機械        ← 相手そのもの（連絡先を持つ）
//	取引先／南北スポーツ機械／現行／… ← その相手の部品
//
// **同じ会社のページが2枚になります**——2026-09-05 の「相手のページは1枚」を
// 意識して覆した結果です。片方は**連絡先の持ち主**、もう片方は**加工製品の置き場**で、
// 役目が違います。⚠ **題だけで結ばれているので、片方を改名すると切れます**
// （参照タグで結ぶのは別の段で入れます）。
// ─────────────────────────────────────────────────────────────────────────

import (

	"w-cms/internal/auth"
	"w-cms/internal/cms"
)

// CustomerBoxTitle は加工製品の階層の根（トップ直下）の名前です。
// **h1（ページ名）が正**——通信箱・テンプレート置き場と同じ「名前が機能」の型。
//
// 2026-10-16 夜に「製造」から「製造台帳」へ改めました（利用者:「トップ直下を製造台帳、年月下を製造記録としては
// どうでしょう？」——品物の台帳と、弊社の動きの記録〔記録／年／月／製造記録〕を名前で分ける）。同じ日の夕方までは「取引先」。
const CustomerBoxTitle = "製造台帳"

// CustomerBoxPageID はトップ直下の製造台帳ページを返します（無ければ ok=false）。
func CustomerBoxPageID() (string, bool) { return cms.TopLevelPageByTitle(CustomerBoxTitle) }

// EnsureCustomerBox は製造台帳ページを返し、**無ければ作ります**。
//
// ただの置き場なので、無いからと整理を行き止まりにする理由がありません
// （アドレス帳の箱と同じ扱い）。管理画面の「置き場」からも作れます。
func EnsureCustomerBox(user *auth.User) (string, error) {
	if id, ok := CustomerBoxPageID(); ok {
		return id, nil
	}
	// **同じ題のテンプレートから作る。無ければ作らない**（2026-09-27・テンプレート駆動）。
	return cms.EnsureTopLevelBox(CustomerBoxTitle, user.Username)
}
