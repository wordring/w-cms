// 続けて:「加工製品ページの部材の表の個数というより、個数の値が小数点の場合、警告として背景色を変えては？
// これを一般化して、名前と値が対応する場合に、ある名前の値の範囲を設定できるように出来ませんか」
//
// 表のセルの警告は、コアの「語の値の範囲」（設定の vocabulary の min・max・integer・画面の背景色）になりました
// ——`個数` に `integer: true` を書いてあります。ここに残るのは、手配状況の表の「一台」の列で、切り上げた数と
// 表の値の両方を見せる所だけです（view_procurement.go の procPer。要る数の切り上げは procurement.go の productNeeds）。
// ─────────────────────────────────────────────────────────────────────────

import "math"

// isFractional は、数が整数でないかを返します。
func isFractional(f float64) bool {
	return math.Abs(f-math.Round(f)) > 1e-9
}
