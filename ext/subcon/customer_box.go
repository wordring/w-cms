package subcon

// ─────────────────────────────────────────────────────────────────────────
// 部品階層の根——`取引先`（2026-09-16 にアドレス帳から分かれた）
//
// ユーザー決定:「**両方を別の木にする**」。それまで1つの箱（`取引先`）が
// **2つの役目**を兼ねていました:
//
//	取引先／社名／段／装置名称／図面名称   ← 部品階層（下請け業務の持ち物）
//	取引先／社名／担当者／氏名             ← アドレス帳（通信の持ち物）
//
// **持ち主が違うものが同じ木に同居していた**ので、分けました。アドレス帳は
// `連絡帳`（`ext/comm/contacts`）、部品階層はこの `取引先` です。
//
// ⚠ **2つの木は「社名の題」で結ばれています。** 整理は差出人アドレスから
// アドレス帳に問い合わせて（`contacts.PartnerTitleForAddress`）**題を受け取り**、
// その題のページをこの木に作ります。つまり:
//
//	連絡帳／南北スポーツ機械        ← 相手そのもの（連絡先を持つ）
//	取引先／南北スポーツ機械／現行／… ← その相手の部品
//
// **同じ会社のページが2枚になります**——2026-09-05 の「相手のページは1枚」を
// 意識して覆した結果です。片方は**連絡先の持ち主**、もう片方は**部品の置き場**で、
// 役目が違います。⚠ **題だけで結ばれているので、片方を改名すると切れます**
// （参照タグで結ぶのは別の段で入れます）。
// ─────────────────────────────────────────────────────────────────────────

import (
	stdhtml "html"

	"w-cms/internal/auth"
	"w-cms/internal/cms"
)

// CustomerBoxTitle は部品階層の根（トップ直下）の名前です。
// **h1（ページ名）が正**——通信箱・テンプレート置き場と同じ「名前が機能」の型。
const CustomerBoxTitle = "取引先"

// CustomerBoxPageID はトップ直下の取引先ページを返します（無ければ ok=false）。
func CustomerBoxPageID() (string, bool) { return cms.TopLevelPageByTitle(CustomerBoxTitle) }

// EnsureCustomerBox は取引先ページを返し、**無ければ作ります**。
//
// ただの置き場なので、無いからと整理を行き止まりにする理由がありません
// （アドレス帳の箱と同じ扱い）。管理画面の「置き場」からも作れます。
func EnsureCustomerBox(user *auth.User) (string, error) {
	if id, ok := CustomerBoxPageID(); ok {
		return id, nil
	}
	return cms.CreateChildPage(cms.TopPageID, user.Username, customerBoxBody())
}

// customerBoxBody は取引先ページの初期の本文です。
//
// ⚠ **作業面はまだありません。** 「どの会社にどれだけ部品があるか」を見るビューが
// 未実装なので、いまは見出しと道案内だけです——**見出しだけの箱は行き止まりになる**
// ので、ビューができたらここへ足すこと（`required_pages.go` の約束）。
func customerBoxBody() string {
	return "<h1>" + stdhtml.EscapeString(CustomerBoxTitle) + "</h1>" +
		"<p>製造部品の階層です（社名／段／装置名称／図面名称）。" +
		"整理を実行すると、通信記録の下にできた部品ページがここへ移ります。</p>" +
		"<p>相手の連絡先（メールアドレス・ドメイン・電話番号）は「連絡帳」にあります" +
		"——こちらは部品の置き場です。</p>"
}
