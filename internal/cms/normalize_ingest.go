// ─────────────────────────────────────────────────────────────────────────
// 取り込み時の正規化（D-3・2026-09-04）
//
// 決定は「**正規化はPDF取り込み時に行い、認識できた形式は背景色で示す**」
// （[docs/アーキテクチャとDBスキーマ.md] §9 の D-3。背景色は 2026-09-01 に実装済み）。
//
// **人が打った値と、機械が書いた値とでは扱いが違います。**
//
//   - 人が打った値は**見た目のまま**保存し、畳んだ値は索引へ併記するだけ
//     （[normalize_text.go] と 生が正本 の原則）。
//   - **機械（PDF解析・取り込み）が本文を書き起こすときは、はじめから正規形で書きます。**
//     書き手がいないので「見た目のまま」に守るべき意図が無く、揃った形で入れたほうが
//     あとの計算も人の読みも楽になるためです。日時の正は ISO 8601
//     （[docs/要件定義書.md] §3）。
//
// 揃えるのは**日付と数値だけ**です。text / code は書かれたまま入れます——
// 図面番号や客先名を機械が畳んで書き換えると、**原本と見比べたときに食い違います**。
//
// 読めなかったら**生のまま**入れます。取り込みは情報を捨てないのが第一で、
// 読めなかったことは（人が見れば分かるので）そのまま残します。
// ─────────────────────────────────────────────────────────────────────────

import "strings"

// CanonicalForIngest は、見出し語に応じて「本文へ書く形」を返します。
//
// 機械が本文を書き起こす経路（PDF解析・`.eml` 取り込み）から呼びます。
// 人の入力には**使いません**。
func CanonicalForIngest(field, raw string) string {
	s := strings.TrimSpace(raw)
	if s == "" {
		return raw
	}
	switch InferColumnType(field) {
	case ColDate, ColNumber:
		if norm, ok := NormalizeValue(InferColumnType(field), s); ok {
			return norm
		}
	}
	return raw // 読めなければ生のまま（情報を捨てない）
}
