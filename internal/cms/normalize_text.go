package cms

// ─────────────────────────────────────────────────────────────────────────
// テキストの正規化——「同じものを同じと認める」ための畳み込み（2026-09-04）
//
// 設計と決定の正本は [docs/【考察】テキストの正規化.md]。要点だけ:
//
//   - **生が正本**。索引の `value` は見た目のまま。畳んだ値は `norm_value` へ**併記**する。
//   - **畳むのは比較のときだけ**。表示には一切影響しない。
//   - 畳む強さは**列型で言い分ける**（案2）:
//       text …… 軽く畳む（全角英数→半角・半角カナ→全角・濁点の合成・前後の空白）
//       code …… 強く畳む（軽い正規化＋空白の除去・ハイフン類/長音/`_`→`-`・英字は大文字）
//
// **なぜ型で分けるか——長音（`ー`）の扱いが値によって正反対だから**です:
//
//	X008ー135（図面番号を全角で打った） → X008-135  …… 正しい
//	レーザーマックス（会社名）           → レ-ザ-マックス …… 壊れている
//
// 同じ関数で両方は扱えません。「畳んでよい値」を code 型として名指しし、
// それ以外の日本語は触らない、というのがこの分割の意味です。
//
// **区切りの有無は畳みません**（`W470-L090` と `W470L090` は別扱い）——
// 畳み過ぎて別の部品を1つにするほうが、取りこぼしより害が大きい。
// ─────────────────────────────────────────────────────────────────────────

import (
	"strings"

	"golang.org/x/text/unicode/norm"
)

// NormalizeText は一般のテキストを軽く畳みます。
//
// 土台は Unicode の NFKC——全角英数→半角（`Ｙ０５０`→`Y050`）、半角カナ→全角
// （`ﾊﾟｲﾌﾟ`→`パイプ`。2026-09-04 ユーザー決定「半角カナは正規化します」）、
// 濁点の分離の合成（`ハ`+`゙`→`バ`）を一度に済ませます。**`ー` には触りません**。
//
// NFKC は `㈱`→`(株)`・`①`→`1` のような踏み込んだ変換も行いますが、
// **比較のためだけの値**なので、同じものとみなせて困りません。
func NormalizeText(s string) string {
	return strings.TrimSpace(norm.NFKC.String(s))
}

// NormalizeCode は図面番号・発注書番号のような**符牒**を強く畳みます。
//
// 畳むのは、実データで実際にぶつかった揺れだけです（拡張の図面番号突き合わせが
// 先に見つけていたもの——`ext/sheetmetal/drawing_match.go`）:
//
//	空白が混ざる          X008-135-4_ 架台Assy
//	`_` がハイフンの位置に  PW050_167-ソレノイド補助具
//	ハイフンの種類         - － ‐ ‑ ‒ – — ー
//	英字の大小            P200-911-03A と p200-911-03a
func NormalizeCode(s string) string {
	var b strings.Builder
	for _, r := range NormalizeText(s) {
		switch {
		case r == ' ' || r == '\t':
			continue // 全角空白は NFKC が半角にしているのでここで落ちる
		case r == '_':
			// **アンダースコアはハイフンとみなす**（消さない）。実データの
			// `PW050_167-ソレノイド補助具` は、ハイフンが来る位置に `_` が入っている。
			b.WriteRune('-')
		case r == '‐' || r == '‑' || r == '‒' ||
			r == '–' || r == '—' || r == 'ー':
			// ハイフン・ダッシュ・長音の類を半角ハイフンへ
			// （全角ハイフン `－` は NFKC が既に `-` にしている）。
			b.WriteRune('-')
		case r >= 'a' && r <= 'z':
			b.WriteRune(r - 'a' + 'A')
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

// NormalizeForLookup は「その見出し語の列型で畳んだ値」を返します。
//
// **索引へ書くときと同じ規則で引くため**の入口です。書き込み側
// （insertVocabEntry）と別々に畳むと、書いた値と引く値が食い違って
// 静かに引けなくなります。
func NormalizeForLookup(field, value string) (string, bool) {
	return NormalizeValue(InferColumnType(field), value)
}
