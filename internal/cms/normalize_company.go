package cms

// ─────────────────────────────────────────────────────────────────────────
// 社名から法人格を落とす——**候補を探すためだけ**の畳み込み（2026-09-20）
//
// ユーザー:「見たままと裏の動作が一致してほしいので、できればページを作る時に
// 表記ゆれを無くしたい。株式会社や有限会社、（株）などを無くした社名が連絡帳に
// あれば、それを提案するような形で、編集者の承認を得てはどうでしょう？
// ちょうどメールの整理のように」。
//
// ── ⚠ これは索引に入りません ──────────────────────────────────────
//
// `NormalizeText`（`char_folding`）は比較値（`norm_value`）に効きますが、こちらは
// **候補を探すときだけ**に使います。落とした形を保存すると、画面の
// 「株式会社南北スポーツ機械」と裏の「南北スポーツ機械」が食い違い、
// **見たままと裏が一致しなくなります**——それを避けるのがこの設計の目的なので、
// ここで保存してしまっては本末転倒です。
//
// ページに入るのは、人が承認した**連絡帳にある実物の題**です。
//
// ── なぜ機械に決めさせないか ──────────────────────────────────────
//
// 「**名寄せを機械にやらせません**。題の完全一致が階層の同一性という根っこは
// 動かしません——揺れを機械が吸収すると、**別の顧客が1つに潰れます**。候補を出す
// ところまでが機械の仕事」（[docs/【考察】アドレス帳の作り直し.md] §7）。
//
// 法人格を落とすと `株式会社あさひ` と `有限会社あさひ` が同じ鍵になります。
// **実在しうる別会社**なので、機械が黙って1つにしてはいけません。だから
// この関数の出口は**提案**で、決めるのは人です。
// ─────────────────────────────────────────────────────────────────────────

import "strings"

// FoldCompanyName は社名から法人格を落として、照合の鍵を作ります。
//
// **前株・後株のどちらも落とします**（`株式会社○○` も `○○(株)` も実データにある）。
// 土台に `NormalizeText` を通すので、`㈱` は先に `(株)` へ開いてから落ちます。
//
// 落とす語は `config/settings.json` の `company_forms` が正本です。
// **未指定なら軽い正規化だけ**で、何も落としません。
//
// 空になったら**畳む前の形**を返します——`株式会社` とだけ書かれたページを、
// 空の鍵で他の全部と同じものにしないためです。
func FoldCompanyName(s string) string {
	v := NormalizeText(s)
	for _, form := range CompanyForms() {
		form = NormalizeText(form)
		if form == "" {
			continue
		}
		// **前と後ろだけ**を落とします。真ん中は落としません——
		// `日本株式会社工業` のような社名を壊さないためです。
		v = strings.TrimSpace(strings.TrimPrefix(v, form))
		v = strings.TrimSpace(strings.TrimSuffix(v, form))
	}
	// 法人格のあとに残る区切り（`株式会社　南北` の中黒や空白）も落とします。
	v = strings.Trim(v, " 　・･")
	if v == "" {
		return NormalizeText(s)
	}
	return v
}

// SameCompany は2つの社名が、法人格を除いて同じかを返します。
//
// **判定ではなく候補の物差し**です（上の注記）。空どうしは同じとみなしません
// ——空の鍵で全部が一致するのを防ぐためです。
func SameCompany(a, b string) bool {
	fa, fb := FoldCompanyName(a), FoldCompanyName(b)
	return fa != "" && fa == fb
}
