// Package extgen は、拡張のフォルダ（ext/ の下）を探して、実行ファイルへの取り付け口（cmd/w-cms/ext_*_gen.go）を作ります
// （2026-10-20・docs/考察/【考察】画面の JS のコアと拡張.md）。
//
// 2026-10-20 利用者:「できれば、拡張をフォルダに入れてビルドすると入るような仕組みが良いです」。
//
// Go は import に書いたパッケージしか組み込まないので、拡張を足すたびに取り付け口（blank import の1行）が要ります。
// それを手で書く代わりに、ビルドの前に `go generate ./cmd/w-cms` で作ります（tools/extgen が呼ぶ）。
//
//   - 拡張とみなすのは、ext/ の下で `cms.RegisterExtension(` を呼ぶパッケージです（試験のファイルは見ない）。
//   - ビルドタグは、拡張が自分で書きます——パッケージのどれかのファイルに `//w-cms:build <式>` の行を置く
//     （例: メールは `!minimal && !nomail`）。無ければ `!minimal`（素の w-cms では外れる・既定は入り）。
//   - 作ったファイルは、リポジトリに入れます（generate を流さなくても `go build` で組み立てられるように）。
//     足し忘れ・消し忘れは、cmd/w-cms の試験（TestExtensionMountsAreGenerated）が見つけます。
package extgen

import (
	"bufio"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// Ext は見つけた拡張1つです。
type Ext struct {
	Dir  string // ext/ からの道（例: comm/mail）
	Tags string // ビルドタグの式
}

var (
	registerRe = regexp.MustCompile(`\bcms\.RegisterExtension\(`)
	tagsRe     = regexp.MustCompile(`^//w-cms:build\s+(.+)$`)
)

// DefaultTags は、拡張が自分でタグを書かなかったときの式です（素の w-cms＝-tags minimal で外れる）。
const DefaultTags = "!minimal"

// Scan は root（リポジトリの根）の ext/ の下から、拡張のパッケージを道の順に返します。
func Scan(root string) ([]Ext, error) {
	base := filepath.Join(root, "ext")
	found := map[string]*Ext{}
	err := filepath.WalkDir(base, func(p string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if name := d.Name(); p != base && (strings.HasPrefix(name, ".") || name == "assets" || name == "testdata") {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(p, ".go") || strings.HasSuffix(p, "_test.go") {
			return nil
		}
		rel, _ := filepath.Rel(base, filepath.Dir(p))
		rel = filepath.ToSlash(rel)
		f, err := os.Open(p)
		if err != nil {
			return err
		}
		defer f.Close()
		sc := bufio.NewScanner(f)
		sc.Buffer(make([]byte, 1024*1024), 1024*1024)
		for sc.Scan() {
			line := sc.Text()
			if m := tagsRe.FindStringSubmatch(strings.TrimSpace(line)); m != nil {
				e := found[rel]
				if e == nil {
					e = &Ext{Dir: rel}
					found[rel] = e
				}
				e.Tags = strings.TrimSpace(m[1])
			}
			if registerRe.MatchString(line) && !strings.HasPrefix(strings.TrimSpace(line), "//") {
				if found[rel] == nil {
					found[rel] = &Ext{Dir: rel}
				}
				found[rel].Dir = rel + "\x00" // 印: RegisterExtension を呼ぶ
			}
		}
		return sc.Err()
	})
	if err != nil {
		return nil, err
	}
	var out []Ext
	for rel, e := range found {
		if !strings.HasSuffix(e.Dir, "\x00") {
			continue // タグの行はあるが、拡張として名乗らないパッケージ
		}
		tags := e.Tags
		if tags == "" {
			tags = DefaultTags
		}
		out = append(out, Ext{Dir: rel, Tags: tags})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Dir < out[j].Dir })
	return out, nil
}

// FileName は拡張の取り付け口のファイルの名前です（例: comm/mail → ext_comm_mail_gen.go）。
func FileName(e Ext) string {
	return "ext_" + strings.ReplaceAll(e.Dir, "/", "_") + "_gen.go"
}

// Content は拡張の取り付け口のファイルの中身です。module は go.mod のモジュールの名前（w-cms）。
func Content(module string, e Ext) string {
	return "// Code generated by tools/extgen; DO NOT EDIT.\n" +
		"// 拡張 ext/" + e.Dir + " の取り付け口です。拡張のフォルダを足し・外したら `go generate ./cmd/w-cms` で作り直します（internal/extgen）。\n\n" +
		"//go:build " + e.Tags + "\n\n" +
		"package main\n\n" +
		"import _ \"" + module + "/ext/" + e.Dir + "\"\n"
}

// Files は、作るべき取り付け口のファイル（名前 → 中身）です。
func Files(module string, exts []Ext) map[string]string {
	out := map[string]string{}
	for _, e := range exts {
		out[FileName(e)] = Content(module, e)
	}
	return out
}

// IsGenerated は、そのファイルの名前が作った取り付け口の形かです（古いものを消すときに使う）。
func IsGenerated(name string) bool {
	return strings.HasPrefix(name, "ext_") && strings.HasSuffix(name, "_gen.go")
}
